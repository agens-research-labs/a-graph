//! The input of a call: a composition of structs, one per kind of content.

use serde_json::Value;

use super::reasoning::Reasoning;
use super::requirements::ProducedMedia;

#[derive(Debug, Clone)]
pub struct ModelInvocation {
    /// Placeholders already resolved by the node.
    pub system: String,
    pub history: Vec<ChatEntry>,
    /// The user prompt, placeholders resolved.
    pub user: String,
    pub media: Vec<MediaInput>,
    pub tools: Vec<ToolDefinition>,
    /// The media the node wants produced, as their resources describe them.
    pub output_media: Vec<ProducedMedia>,
    /// The output schema, as a JSON object.
    pub schema: Option<Value>,
    /// Absent = not sent: the provider applies its own default.
    pub temperature: Option<f64>,
    pub top_p: Option<f64>,
    pub max_tokens: Option<u32>,
    pub reasoning: Option<Reasoning>,
    /// Empty on the first call; the node adds one round per pass of the tool loop.
    pub tool_rounds: Vec<ToolRound>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Role {
    User,
    Assistant,
}

#[derive(Debug, Clone)]
pub struct ChatEntry {
    pub role: Role,
    pub content: String,
}

/// Already loaded and encoded: reading a path or url is not the models module's job.
#[derive(Debug, Clone)]
pub enum MediaInput {
    Markdown(String),
    Image { format: String, data: String },
}

#[derive(Debug, Clone)]
pub struct ToolDefinition {
    pub name: String,
    pub description: String,
    /// The raw JSON Schema of the parameters: each provider puts it in its own field.
    pub parameters: Value,
}

#[derive(Debug, Clone)]
pub struct ToolRound {
    /// What the model said before asking for the tools.
    pub message: Option<String>,
    /// The original provider blocks, opaque: sent back as they came.
    pub reasoning: Vec<Value>,
    pub calls: Vec<ToolCall>,
    pub results: Vec<ToolResult>,
}

#[derive(Debug, Clone, PartialEq)]
pub struct ToolCall {
    /// Generated by the trait when the provider gives none.
    pub call_id: String,
    pub function_name: String,
    /// Always an object (a provider's JSON string is converted).
    pub arguments: Value,
    /// Provider data to send back with the call as it came (e.g. a signature); opaque.
    pub opaque: Option<Value>,
}

#[derive(Debug, Clone, PartialEq)]
pub struct ToolResult {
    pub call_id: String,
    pub result: Value,
    pub is_error: bool,
}
